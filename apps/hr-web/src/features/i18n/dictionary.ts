/**
 * UI strings for the two supported languages.
 *
 * `en` is the source of truth: its keys define `TKey`, so `ar` cannot drift or
 * miss an entry without a type error. Values may use `{placeholders}`, and an
 * object value is a plural entry resolved with Intl.PluralRules (see t()).
 */

export type Lang = 'en' | 'ar'
export type Dir = 'ltr' | 'rtl'

/** CLDR plural categories. Arabic uses all six; English only one/other. */
export type PluralRule = 'zero' | 'one' | 'two' | 'few' | 'many' | 'other'
export type PluralEntry = Partial<Record<PluralRule, string>> & { other: string }
export type Entry = string | PluralEntry

/**
 * A value substituted into a `{placeholder}`. A Date is formatted with the
 * current locale, and a nested Message is translated first — which is how data
 * carries things like "3 أيام" or a date range without knowing the language.
 */
export type Var = string | number | Date | Message

/** A translatable string plus its values, so data can carry messages around. */
export interface Message {
  key: TKey
  vars?: Record<string, Var>
}

/** Free text that lives in data rather than in the dictionary (names, titles). */
export interface Localized {
  en: string
  ar: string
}

