/**
 * The only place the app talks to the API.
 *
 * Every call carries the session cookie and nothing else: there is no token in
 * `localStorage` for a script to read, and no credential in the bundle. A failed
 * call throws an {@link ApiError} carrying the machine-readable code the server
 * sent, which the UI translates like any other string.
 */

const BASE = import.meta.env.VITE_API_URL ?? '/api'

export class ApiError extends Error {
  readonly status: number
  /** A dictionary-friendly code, e.g. `invalidCredentials`. */
  readonly code: string
  readonly details?: Record<string, string[]>
  /** Extra payload some endpoints attach, such as the leave rejection reason. */
  readonly payload?: unknown
  /**
   * The fields an endpoint said were missing, when it named them.
   *
   * Publishing a vacancy refuses with the exact list \u2014 location,
   * employmentType \u2014 and this was being dropped on the floor, so the message
   * read "fill in the title, department, location and employment type" for two
   * empty boxes out of four. The server knew which two.
   */
  readonly missing?: string[]
  /**
   * Seconds until the caller may retry, from the server's `Retry-After`.
   *
   * Carried because a rate-limit message that guesses is worse than none: "wait
   * a few minutes" when the window is an hour teaches people the message is not
   * to be believed.
   */
  readonly retryAfter?: number

  constructor(
    status: number,
    code: string,
    message: string,
    extra?: { details?: Record<string, string[]>; payload?: unknown; retryAfter?: number; missing?: string[] },
  ) {
    super(message)
    this.name = 'ApiError'
    this.status = status
    this.code = code
    this.details = extra?.details
    this.payload = extra?.payload
    this.missing = extra?.missing
    this.retryAfter = extra?.retryAfter
  }

  /** True when the session is gone and the app should return to the login page. */
  get isUnauthenticated() {
    return this.status === 401
  }
}

async function request<T>(path: string, init?: RequestInit): Promise<T> {
  let response: Response
  try {
    response = await fetch(`${BASE}${path}`, {
      ...init,
      // Without this the browser omits the session cookie.
      credentials: 'include',
      headers: {
        // FormData must set its own Content-Type: the multipart boundary is
        // generated by the browser, and naming the type here strips it, leaving
        // the server unable to parse a body it can see perfectly well.
        ...(init?.body && !(init.body instanceof FormData) ? { 'Content-Type': 'application/json' } : {}),
        ...init?.headers,
      },
    })
  } catch (caught) {
    // Callers that deliberately cancel a superseded request need to be able to
    // tell that apart from a real offline/API failure.  In particular, Voice
    // Copilot abandons an unfinished *read/proposal* turn as soon as the person
    // starts a new sentence, so the latest command never waits behind it.
    if (init?.signal?.aborted) throw caught
    // A network failure is not a server error, and must not read as one.
    throw new ApiError(0, 'networkUnavailable', 'Could not reach the server.')
  }

  if (response.status === 204) return undefined as T

  const text = await response.text()
  const body = text ? safeJson(text) : null

  if (!response.ok) {
    const record = (body ?? {}) as Record<string, unknown>
    throw new ApiError(
      response.status,
      typeof record.error === 'string' ? record.error : 'requestFailed',
      typeof record.message === 'string' ? record.message : response.statusText,
      {
        details: record.details as Record<string, string[]> | undefined,
        payload: record.problem,
        missing: Array.isArray(record.missing) ? (record.missing as string[]) : undefined,
        retryAfter: Number(response.headers.get('retry-after')) || undefined,
      },
    )
  }

  return body as T
}

function safeJson(text: string): unknown {
  try {
    return JSON.parse(text)
  } catch {
    return null
  }
}

export const api = {
  get: <T>(path: string) => request<T>(path),
  post: <T>(path: string, body?: unknown, options?: Pick<RequestInit, 'signal'>) =>
    request<T>(path, { method: 'POST', body: body === undefined ? undefined : JSON.stringify(body), signal: options?.signal }),
  /** Raw, non-JSON request for the WebRTC SDP offer. */
  postText: <T>(path: string, body: string, contentType = 'text/plain') =>
    request<T>(path, { method: 'POST', body, headers: { 'Content-Type': contentType } }),
  /** Replaces a whole thing, where a merge would leave half of it behind. */
  put: <T>(path: string, body: unknown) =>
    request<T>(path, { method: 'PUT', body: JSON.stringify(body) }),
  patch: <T>(path: string, body: unknown) =>
    request<T>(path, { method: 'PATCH', body: JSON.stringify(body) }),
  delete: <T>(path: string) => request<T>(path, { method: 'DELETE' }),
  /** Multipart POST, for file uploads. Errors surface as {@link ApiError} like any other call. */
  upload: <T>(path: string, form: FormData) => request<T>(path, { method: 'POST', body: form }),
}

/**
 * The URL a download link points at.
 *
 * Downloads are plain navigations rather than fetches: the cookie rides along
 * because the API is same-origin through the dev proxy, and the browser's own
 * save dialog handles the file — no blob in memory, no object URL to revoke.
 */
export function downloadUrl(path: string): string {
  return `${BASE}${path}`
}

/** Builds `?a=1&b=2`, dropping anything unset so the server sees a clean query. */
export function query(params: Record<string, string | number | boolean | undefined>): string {
  const search = new URLSearchParams()
  for (const [key, value] of Object.entries(params)) {
    if (value !== undefined && value !== '') search.set(key, String(value))
  }
  const s = search.toString()
  return s ? `?${s}` : ''
}
